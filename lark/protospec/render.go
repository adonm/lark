// File is one generated output, rooted at the repository root.
type File struct {
	Path    string
	Content []byte
}

// Render generates every output. It is deterministic; the drift guard compares
// these bytes against the committed files.
func Render() ([]File, error) {
	protoSrc, err := renderGoFile("proto")
	if err != nil {
		return nil, err
	}
	cSrc, err := renderC()
	if err != nil {
		return nil, err
	}
	docs, err := renderDocs()
	if err != nil {
		return nil, err
	}
	fixGo, err := renderGoFixtures()
	if err != nil {
		return nil, err
	}
	fixC, err := renderCFixtures()
	if err != nil {
		return nil, err
	}
	return []File{
		{Path: "firmware/main/proto.h", Content: cSrc},
		{Path: "firmware/tests/testdata/proto_fixtures.h", Content: fixC},
		{Path: "lark/internal/proto/proto_gen.go", Content: protoSrc},
		{Path: "lark/protospec/fixtures_gen.go", Content: fixGo},
		{Path: "docs/protocol.md", Content: docs},
	}, nil
}

const header = "// Code generated by lark/protospec/cmd/protogen from spec.go; DO NOT EDIT.\n"

func lowerFirst(s string) string {
	if s == "" {
		return s
	}
	return strings.ToLower(s[:1]) + s[1:]
}

func upperSnake(s string) string { return snakeUpper(s) }

func goConstValue(c Const) string {
	if c.Flag {
		return fmt.Sprintf("1 << %d", c.Bit)
	}
	return fmt.Sprintf("%d", c.Value)
}

func cConstValue(c Const) string {
	if c.Flag {
		return fmt.Sprintf("1u << %d", c.Bit)
	}
	return fmt.Sprintf("%d", c.Value)
}

func decodeName(m Message) string {
	return "decode" + strings.ToUpper(m.GoName[:1]) + m.GoName[1:]
}

// goStyle names identifiers for the generated proto package. Every identifier
// is exported so internal/edge and the tests share one generated codec.
type goStyle struct{ pkg string }

func (s goStyle) name(v string) string {
	if v == "" {
		return v
	}
	return strings.ToUpper(v[:1]) + v[1:]
}

func (s goStyle) typeName(m Message) string { return s.name(m.GoName) }
func (s goStyle) msgName(m Message) string  { return s.name(m.MsgGo) }
func (s goStyle) fieldName(f Field) string  { return s.name(f.Go) }
func (s goStyle) encodeName() string          { return "Encode" }
func (s goStyle) decodeName(m Message) string { return s.name(decodeName(m)) }

func renderGoFile(pkg string) ([]byte, error) {
	s := goStyle{pkg: pkg}
	var b bytes.Buffer
	b.WriteString(header)
	fmt.Fprintf(&b, "\npackage %s\n\nimport (\n\t\"encoding/binary\"\n)\n\n", pkg)

	b.WriteString("// Protocol constants.\nconst (\n")
	for _, c := range Constants {
		if !c.HasGo() {
			continue
		}
		if c.Doc != "" {
			fmt.Fprintf(&b, "\t// %s\n", c.Doc)
		}
		fmt.Fprintf(&b, "\t%s = %s\n", s.name(c.Go), goConstValue(c))
	}
	b.WriteString(")\n\n")

	b.WriteString("// Message type bytes.\nconst (\n")
	for _, m := range Messages {
		fmt.Fprintf(&b, "\t%s uint8 = 0x%02X\n", s.msgName(m), m.TypeByte)
	}
	b.WriteString(")\n\n")

	for _, m := range Messages {
		typeName := s.typeName(m)
		b.WriteString("// " + m.Name + ": " + m.Doc + "\n")
		fmt.Fprintf(&b, "type %s struct {\n", typeName)
		if m.Opaque {
			b.WriteString("\tpayload []byte\n")
		}
		for _, f := range m.Fields {
			doc := f.Doc
			if f.Retired && doc == "" {
				doc = "retired"
			}
			if doc != "" {
				fmt.Fprintf(&b, "\t// %s\n", doc)
			}
			switch f.Kind {
			case Str8, Str16:
				fmt.Fprintf(&b, "\t%s string\n", s.fieldName(f))
			case Bytes:
				fmt.Fprintf(&b, "\t%s [%d]byte\n", s.fieldName(f), f.Count)
			default:
				fmt.Fprintf(&b, "\t%s %s\n", s.fieldName(f), goScalar(f.Kind))
			}
		}
		b.WriteString("}\n\n")
		if m.Opaque {
			fmt.Fprintf(&b, "func (m %s) %s() []byte { return append([]byte(nil), m.payload...) }\n", typeName, s.encodeName())
			fmt.Fprintf(&b, "func %s(b []byte) (%s, bool) { return %s{payload: b}, true }\n\n", s.decodeName(m), typeName, typeName)
			continue
		}
		fmt.Fprintf(&b, "const %sFixedSize = %d\n", typeName, m.FixedSize())
		off := 0
		for _, f := range m.Fields {
			fmt.Fprintf(&b, "const %s%sOff = %d\n", typeName, s.fieldName(f), off)
			off += f.Size()
		}
		b.WriteString("\n")

		// encode
		fmt.Fprintf(&b, "func (m %s) %s() []byte {\n", typeName, s.encodeName())
		// String prefixes are part of the fixed prefix; bodies follow it.
		vi := 0
		for _, f := range m.Fields {
			if !f.Variable() {
				continue
			}
			limit := 255
			if f.Kind == Str16 {
				limit = 65535
			}
			arg := "m." + s.fieldName(f)
			if f.Retired {
				arg = `""`
			}
			fmt.Fprintf(&b, "\ts%d := %s\n", vi, arg)
			fmt.Fprintf(&b, "\tif len(s%d) > %d {\n\t\ts%d = s%d[:%d]\n\t}\n", vi, limit, vi, vi, limit)
			vi++
		}
		fmt.Fprintf(&b, "\tb := make([]byte, 0, %sFixedSize", typeName)
		for _, f := range m.Fields {
			if f.Variable() && !f.Retired {
				fmt.Fprintf(&b, "+len(m.%s)", s.fieldName(f))
			}
		}
		b.WriteString(")\n")
		for _, f := range m.Fields {
			if f.Variable() {
				continue
			}
			if f.Retired {
				switch f.Kind {
				case U8:
					b.WriteString("\tb = append(b, 0)\n")
				case U16, I16:
					b.WriteString("\tb = binary.LittleEndian.AppendUint16(b, 0)\n")
				case U32:
					b.WriteString("\tb = binary.LittleEndian.AppendUint32(b, 0)\n")
				case U64:
					b.WriteString("\tb = binary.LittleEndian.AppendUint64(b, 0)\n")
				case Bytes:
					fmt.Fprintf(&b, "\tb = append(b, make([]byte, %d)...)\n", f.Count)
				}
				continue
			}
			switch f.Kind {
			case U8:
				fmt.Fprintf(&b, "\tb = append(b, m.%s)\n", s.fieldName(f))
			case U16:
				fmt.Fprintf(&b, "\tb = binary.LittleEndian.AppendUint16(b, m.%s)\n", s.fieldName(f))
			case I16:
				fmt.Fprintf(&b, "\tb = binary.LittleEndian.AppendUint16(b, uint16(m.%s))\n", s.fieldName(f))
			case U32:
				fmt.Fprintf(&b, "\tb = binary.LittleEndian.AppendUint32(b, m.%s)\n", s.fieldName(f))
			case U64:
				fmt.Fprintf(&b, "\tb = binary.LittleEndian.AppendUint64(b, m.%s)\n", s.fieldName(f))
			case Bytes:
				fmt.Fprintf(&b, "\tb = append(b, m.%s[:]...)\n", s.fieldName(f))
			}
		}
		vi = 0
		for _, f := range m.Fields {
			if !f.Variable() {
				continue
			}
			if f.Kind == Str8 {
				fmt.Fprintf(&b, "\tb = append(b, byte(len(s%d)))\n", vi)
			} else {
				fmt.Fprintf(&b, "\tb = binary.LittleEndian.AppendUint16(b, uint16(len(s%d)))\n", vi)
			}
			vi++
		}
		vi = 0
		for _, f := range m.Fields {
			if !f.Variable() {
				continue
			}
			fmt.Fprintf(&b, "\tb = append(b, s%d...)\n", vi)
			vi++
		}
		b.WriteString("\treturn b\n}\n\n")

		// decode
		fmt.Fprintf(&b, "func %s(b []byte) (%s, bool) {\n", s.decodeName(m), typeName)
		fmt.Fprintf(&b, "\tvar m %s\n", typeName)
		fmt.Fprintf(&b, "\tif len(b) < %sFixedSize {\n\t\treturn m, false\n\t}\n", typeName)
		for _, f := range m.Fields {
			if f.Variable() {
				continue
			}
			c := fmt.Sprintf("%s%sOff", typeName, s.fieldName(f))
			switch f.Kind {
			case U8:
				fmt.Fprintf(&b, "\tm.%s = b[%s]\n", s.fieldName(f), c)
			case U16:
				fmt.Fprintf(&b, "\tm.%s = binary.LittleEndian.Uint16(b[%s : %s+2])\n", s.fieldName(f), c, c)
			case I16:
				fmt.Fprintf(&b, "\tm.%s = int16(binary.LittleEndian.Uint16(b[%s : %s+2]))\n", s.fieldName(f), c, c)
			case U32:
				fmt.Fprintf(&b, "\tm.%s = binary.LittleEndian.Uint32(b[%s : %s+4])\n", s.fieldName(f), c, c)
			case U64:
				fmt.Fprintf(&b, "\tm.%s = binary.LittleEndian.Uint64(b[%s : %s+8])\n", s.fieldName(f), c, c)
			case Bytes:
				fmt.Fprintf(&b, "\tcopy(m.%s[:], b[%s:%s+%d])\n", s.fieldName(f), c, c, f.Count)
			}
		}
		hasVar := false
		for _, f := range m.Fields {
			if f.Variable() {
				hasVar = true
			}
		}
		if hasVar {
			fmt.Fprintf(&b, "\toff := %sFixedSize\n", typeName)
			vi := 0
			for _, f := range m.Fields {
				if !f.Variable() {
					continue
				}
				lenOff := fmt.Sprintf("%s%sOff", typeName, s.fieldName(f))
				if f.Kind == Str8 {
					fmt.Fprintf(&b, "\tn%d := int(b[%s])\n", vi, lenOff)
				} else {
					fmt.Fprintf(&b, "\tn%d := int(binary.LittleEndian.Uint16(b[%s : %s+2]))\n", vi, lenOff, lenOff)
				}
				fmt.Fprintf(&b, "\tif off+n%d > len(b) {\n\t\treturn m, false\n\t}\n", vi)
				fmt.Fprintf(&b, "\tm.%s = string(b[off : off+n%d])\n", s.fieldName(f), vi)
				fmt.Fprintf(&b, "\toff += n%d\n", vi)
				vi++
			}
		}
		b.WriteString("\treturn m, true\n}\n\n")
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated Go: %w", err)
	}
	return src, nil
}

func goScalar(k Kind) string {
	switch k {
	case U8:
		return "uint8"
	case U16:
		return "uint16"
	case U32:
		return "uint32"
	case U64:
		return "uint64"
	case I16:
		return "int16"
	}
	return "uint8"
}

func renderC() ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString(`
#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include <stdlib.h>
#include <string.h>

`)
	// Constants, grouped by doc where given.
	b.WriteString("enum {\n")
	first := true
	for _, c := range Constants {
		if !c.HasC() {
			continue
		}
		if c.Doc != "" {
			if !first {
				b.WriteString("\n")
			}
			fmt.Fprintf(&b, "    // %s\n", c.Doc)
		}
		fmt.Fprintf(&b, "    %s = %s,\n", c.C, cConstValue(c))
		first = false
	}
	b.WriteString("};\n\n")

	b.WriteString("// Message type bytes.\nenum {\n")
	for _, m := range Messages {
		fmt.Fprintf(&b, "    %s = 0x%02X,\n", m.MsgC, m.TypeByte)
	}
	b.WriteString("};\n\n")

	for _, m := range Messages {
		if m.Opaque {
			continue
		}
		fmt.Fprintf(&b, "// %s (0x%02X): %s\n", upperSnake(m.Name), m.TypeByte, m.Doc)
		b.WriteString("typedef struct __attribute__((packed)) {\n")
		for _, f := range m.Fields {
			doc := f.Doc
			if f.Retired && doc == "" {
				doc = "retired"
			}
			if doc != "" {
				fmt.Fprintf(&b, "    // %s\n", doc)
			}
			switch f.Kind {
			case Bytes:
				fmt.Fprintf(&b, "    %s %s[%d];\n", f.CType(), f.C, f.Count)
			default:
				fmt.Fprintf(&b, "    %s %s;\n", f.CType(), f.C)
			}
		}
		fmt.Fprintf(&b, "} %s;\n\n", m.CName)
	}

	b.WriteString("// Envelope header.\ntypedef struct __attribute__((packed)) {\n")
	b.WriteString("    uint8_t magic;\n    uint8_t type;\n    uint16_t seq;\n    uint32_t length;\n} lark_hdr_t;\n\n")
	b.WriteString("_Static_assert(sizeof(lark_hdr_t) == 8, \"lark_hdr_t must be 8 bytes\");\n")
	for _, m := range Messages {
		if m.Opaque {
			continue
		}
		fmt.Fprintf(&b, "_Static_assert(sizeof(%s) == %d, \"%s must be %d bytes\");\n",
			m.CName, m.FixedSize(), m.CName, m.FixedSize())
	}
	b.WriteString("\n")

	// Field offsets.
	b.WriteString("// Packed field offsets.\nenum {\n")
	for _, m := range Messages {
		if m.Opaque {
			continue
		}
		off := 0
		for _, f := range m.Fields {
			fmt.Fprintf(&b, "    LARK_%s_%s_OFF = %d,\n", upperSnake(m.Name), upperSnake(f.C), off)
			off += f.Size()
		}
	}
	b.WriteString("};\n\n")

	for _, m := range Messages {
		if m.Opaque {
			continue
		}
		renderCEncode(&b, m)
		renderCDecode(&b, m)
	}
	b.WriteString("// Hand-written envelope, RTP and URL helpers.\n#include \"proto_util.h\"\n")
	return b.Bytes(), nil
}

func cStringArgs(m Message) string {
	var parts []string
	for _, f := range m.Fields {
		if f.Variable() && !f.Retired {
			parts = append(parts, fmt.Sprintf("const char *%s", f.Go))
		}
	}
	if len(parts) == 0 {
		return ""
	}
	return ", " + strings.Join(parts, ", ")
}

func cOutArgs(m Message) string {
	var parts []string
	for _, f := range m.Fields {
		if f.Variable() && !f.Retired {
			parts = append(parts, fmt.Sprintf("char *%s, size_t %s_cap", f.Go, f.Go))
		}
	}
	if len(parts) == 0 {
		return ""
	}
	return ", " + strings.Join(parts, ", ")
}

func cFuncName(m Message) string {
	return strings.ToLower(upperSnake(m.Name))
}

func renderCEncode(b *bytes.Buffer, m Message) {
	fmt.Fprintf(b, "static inline size_t lark_encode_%s(uint8_t *dst, size_t cap, const %s *m%s)\n{\n",
		cFuncName(m), m.CName, cStringArgs(m))
	b.WriteString("    if (!dst || !m) return 0;\n")
	fmt.Fprintf(b, "    %s tmp = *m;\n", m.CName)
	// Zero retired fields in the copy so they never leak onto the wire.
	for _, f := range m.Fields {
		if !f.Retired {
			continue
		}
		if f.Variable() {
			fmt.Fprintf(b, "    tmp.%s = 0;\n", f.CLen)
		} else {
			fmt.Fprintf(b, "    memset(&tmp.%s, 0, sizeof(tmp.%s));\n", f.C, f.C)
		}
	}
	for _, f := range m.Fields {
		if !f.Variable() || f.Retired {
			continue
		}
		var max int
		if f.Kind == Str8 {
			max = 255
		} else {
			max = 65535
		}
		fmt.Fprintf(b, "    size_t %s_len = %s ? strlen(%s) : 0;\n", f.Go, f.Go, f.Go)
		fmt.Fprintf(b, "    if (%s_len > %d) %s_len = %d;\n", f.Go, max, f.Go, max)
		if f.Kind == Str8 {
			fmt.Fprintf(b, "    tmp.%s = (uint8_t)%s_len;\n", f.CLen, f.Go)
		} else {
			fmt.Fprintf(b, "    tmp.%s = (uint16_t)%s_len;\n", f.CLen, f.Go)
		}
	}
	b.WriteString("    size_t total = sizeof(tmp)")
	for _, f := range m.Fields {
		if f.Variable() && !f.Retired {
			fmt.Fprintf(b, " + %s_len", f.Go)
		}
	}
	b.WriteString(";\n    if (total > cap) return 0;\n    memcpy(dst, &tmp, sizeof(tmp));\n")
	hasBody := false
	for _, f := range m.Fields {
		if f.Variable() && !f.Retired {
			hasBody = true
		}
	}
	if hasBody {
		b.WriteString("    size_t off = sizeof(tmp);\n")
	}
	for _, f := range m.Fields {
		if !f.Variable() || f.Retired {
			continue
		}
		fmt.Fprintf(b, "    if (%s_len) memcpy(dst + off, %s, %s_len);\n", f.Go, f.Go, f.Go)
		fmt.Fprintf(b, "    off += %s_len;\n", f.Go)
	}
	b.WriteString("    return total;\n}\n\n")
}

func renderCDecode(b *bytes.Buffer, m Message) {
	fmt.Fprintf(b, "static inline bool lark_decode_%s(const uint8_t *src, size_t len, %s *out%s)\n{\n",
		cFuncName(m), m.CName, cOutArgs(m))
	b.WriteString("    if (!src || !out || len < sizeof(*out)) return false;\n    memcpy(out, src, sizeof(*out));\n")
	hasVar := false
	for _, f := range m.Fields {
		if f.Variable() {
			hasVar = true
			break
		}
	}
	if hasVar {
		b.WriteString("    size_t need = sizeof(*out)")
		for _, f := range m.Fields {
			if f.Variable() {
				fmt.Fprintf(b, " + out->%s", f.CLen)
			}
		}
		b.WriteString(";\n    if (len < need) return false;\n    size_t off = sizeof(*out);\n")
		for _, f := range m.Fields {
			if !f.Variable() {
				continue
			}
			if !f.Retired {
				fmt.Fprintf(b, "    if (%s && %s_cap) {\n", f.Go, f.Go)
				fmt.Fprintf(b, "        size_t n = out->%s < %s_cap - 1 ? out->%s : %s_cap - 1;\n", f.CLen, f.Go, f.CLen, f.Go)
				fmt.Fprintf(b, "        if (n) memcpy(%s, src + off, n);\n        %s[n] = '\\0';\n    }\n", f.Go, f.Go)
			}
			fmt.Fprintf(b, "    off += out->%s;\n", f.CLen)
		}
	}
	b.WriteString("    return true;\n}\n\n")
}

func renderDocs() ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("# Terminal wire protocol\n\n")
	b.WriteString("Generated from `lark/protospec/spec.go` by `go generate ./...`; do not edit.\n\n")
	b.WriteString("## Envelope\n\n")
	b.WriteString("Every message is an 8-byte little-endian envelope followed by the payload:\n\n")
	b.WriteString("| Field | Type | Width |\n| --- | --- | --- |\n")
	b.WriteString("| magic | u8 | 1 |\n| type | u8 | 1 |\n| seq | u16 | 2 |\n| length | u32 | 4 |\n\n")
	b.WriteString("`magic` is `0x4C`; payloads above 320 KiB are rejected.\n\n")
	b.WriteString("## Messages\n\n")
	for _, m := range Messages {
		dir := "terminal → Lark"
		if m.ToDevice {
			dir = "Lark → terminal"
		}
		fmt.Fprintf(&b, "### 0x%02X %s (%s)\n\n%s\n\n", m.TypeByte, upperSnake(m.Name), dir, m.Doc)
		if m.Opaque {
			b.WriteString("Variable-length payload described by its own codec.\n\n")
			continue
		}
		fmt.Fprintf(&b, "Fixed size: %d bytes.\n\n", m.FixedSize())
		b.WriteString("| Offset | Field | Type | Width | Notes |\n| --- | --- | --- | --- | --- |\n")
		off := 0
		for _, f := range m.Fields {
			typ := f.Kind.String()
			if f.Kind == Bytes {
				typ = "bytes"
			}
			notes := f.Doc
			if f.Retired && !strings.Contains(notes, "retired") {
				if notes != "" {
					notes = "retired: " + notes
				} else {
					notes = "retired"
				}
			}
			fmt.Fprintf(&b, "| %d | %s | %s | %d | %s |\n", off, f.C, typ, f.Size(), notes)
			off += f.Size()
		}
		hasVar := false
		for _, f := range m.Fields {
			if f.Variable() {
				hasVar = true
			}
		}
		if hasVar {
			b.WriteString("\nLength-prefixed string fields follow the fixed prefix in table order.\n")
		}
		b.WriteString("\n")
	}
	b.WriteString("## Constants\n\n| Go | C | Value |\n| --- | --- | --- |\n")
	for _, c := range Constants {
		v := fmt.Sprintf("%d", c.Value)
		if c.Flag {
			v = fmt.Sprintf("1 << %d", c.Bit)
		}
		goName, cName := c.Go, c.C
		if goName == "" {
			goName = "—"
		}
		if cName == "" {
			cName = "—"
		}
		fmt.Fprintf(&b, "| `%s` | `%s` | %s |\n", goName, cName, v)
	}
	return b.Bytes(), nil
}

func sampleMessage(m Message) []byte {
	var b []byte
	// Fixed prefix: all scalar and byte fields come before string fields.
	for _, f := range m.Fields {
		if f.Variable() {
			continue
		}
		if f.Retired {
			b = append(b, make([]byte, f.Size())...)
			continue
		}
		switch f.Kind {
		case U8:
			b = append(b, byte(f.Sample))
		case U16:
			b = binary.LittleEndian.AppendUint16(b, uint16(f.Sample))
		case I16:
			b = binary.LittleEndian.AppendUint16(b, uint16(int16(f.Sample)))
		case U32:
			b = binary.LittleEndian.AppendUint32(b, uint32(f.Sample))
		case U64:
			b = binary.LittleEndian.AppendUint64(b, uint64(f.Sample))
		case Bytes:
			raw := append([]byte(nil), f.Bytes...)
			for len(raw) < f.Count {
				raw = append(raw, 0)
			}
			b = append(b, raw[:f.Count]...)
		}
	}
	for _, f := range m.Fields {
		if !f.Variable() {
			continue
		}
		s := f.Str
		if f.Retired {
			s = ""
		}
		if f.Kind == Str8 {
			n := len(s)
			if n > 255 {
				n = 255
			}
			b = append(b, byte(n))
		} else {
			n := len(s)
			if n > 65535 {
				n = 65535
			}
			b = binary.LittleEndian.AppendUint16(b, uint16(n))
		}
	}
	for _, f := range m.Fields {
		if !f.Variable() {
			continue
		}
		s := f.Str
		if f.Retired {
			s = ""
		}
		if f.Kind == Str8 && len(s) > 255 {
			s = s[:255]
		}
		if f.Kind == Str16 && len(s) > 65535 {
			s = s[:65535]
		}
		b = append(b, s...)
	}
	return b
}

func renderGoFixtures() ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("\npackage protospec\n\n// Fixture is a Go-encoded message used by host round-trip tests.\ntype Fixture struct {\n\tName     string\n\tTypeByte uint8\n\tBytes    []byte\n}\n\nvar Fixtures = []Fixture{\n")
	for _, m := range Messages {
		if m.Opaque {
			continue
		}
		fmt.Fprintf(&b, "\t{Name: %q, TypeByte: 0x%02X, Bytes: []byte{", m.Name, m.TypeByte)
		for i, v := range sampleMessage(m) {
			if i%12 == 0 {
				b.WriteString("\n\t\t")
			}
			fmt.Fprintf(&b, "0x%02X, ", v)
		}
		b.WriteString("\n\t}},\n")
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated fixtures: %w", err)
	}
	return src, nil
}

func renderCFixtures() ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString(`
#include <stdint.h>

// Byte-for-byte fixtures produced by the Go codec, plus the sample field
// values used to build each one.
`)
	for _, m := range Messages {
		if m.Opaque {
			continue
		}
		id := strings.ToLower(upperSnake(m.Name))
		fmt.Fprintf(&b, "\nstatic const uint8_t proto_fixture_%s[] = {", id)
		for i, v := range sampleMessage(m) {
			if i%12 == 0 {
				b.WriteString("\n    ")
			}
			fmt.Fprintf(&b, "0x%02X, ", v)
		}
		fmt.Fprintf(&b, "\n};\nenum { PROTO_FIXTURE_%s_LEN = %d };\n", upperSnake(m.Name), len(sampleMessage(m)))
		for _, f := range m.Fields {
			macro := fmt.Sprintf("FIXTURE_%s_%s", upperSnake(m.Name), upperSnake(f.C))
			switch f.Kind {
			case Str8, Str16:
				fmt.Fprintf(&b, "#define %s %q\n", macro, f.Str)
			case Bytes:
				// Byte arrays are checked through the struct decode.
			default:
				fmt.Fprintf(&b, "#define %s %d\n", macro, f.Sample)
			}
		}
	}
	return b.Bytes(), nil
}

// SortedNames is used by tests and callers that need a stable message list.
func SortedNames() []string {
	names := make([]string, 0, len(Messages))
	for _, m := range Messages {
		names = append(names, m.Name)
	}
	sort.Strings(names)
	return names
}
