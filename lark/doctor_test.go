func doctorFixture(t *testing.T, mutate map[string]any) *httptest.Server {
	t.Helper()
	body := map[string]any{
		"/health": map[string]any{"ok": true, "opencode": true, "stt": true, "tts": true,
			"smart_turn": true, "deltachat": true, "stt_engine": "parakeet", "tts_engine": "kokoro"},
		"/api/companions": map[string]any{"companions": []any{
			map[string]any{"id": "mint", "dc_account_id": 1},
			map[string]any{"id": "cake", "dc_account_id": 2},
		}},
		"/api/terminals": map[string]any{"terminals": []any{
			map[string]any{"id": "box3-test", "board": "esp-box-3", "firmware": "9.9.9", "online": true, "ip": "127.0.0.1"},
		}},
		"/api/library": map[string]any{"total_bytes": 100 << 30, "free_bytes": 90 << 30, "reserve_bytes": 20 << 30,
			"packs": []any{
				map[string]any{"name": "gutenberg", "state": "installed", "installed_bytes": 1 << 30},
				map[string]any{"name": "simple", "state": "installed", "installed_bytes": 500 << 20},
				map[string]any{"name": "enwiki", "state": "installed", "installed_bytes": 30 << 30},
			}},
		"/api/remote/tunnels": map[string]any{"tunnels": []any{
			map[string]any{"companion_id": "mint", "active": true},
		}},
		"/api/diagnostics": map[string]any{"recent_turns": []any{
			map[string]any{"source": "voice"},
			map[string]any{"source": "voice"},
		}},
	}
	for path, value := range mutate {
		body[path] = value
	}
	return httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		value, ok := body[r.URL.Path]
		if !ok {
			http.NotFound(w, r)
			return
		}
		_ = json.NewEncoder(w).Encode(value)
	}))
}

func doctorTestEnv(t *testing.T) doctor {
	t.Helper()
	repo := t.TempDir()
	if err := os.MkdirAll(filepath.Join(repo, "firmware", "build-box3"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(repo, "firmware", "CMakeLists.txt"), []byte("project(lark)\nset(PROJECT_VER \"9.9.9\")\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(repo, "firmware", "build-box3", "project_description.json"),
		[]byte(`{"project_version": "9.9.9"}`), 0o644); err != nil {
		t.Fatal(err)
	}
	config := filepath.Join(repo, "opencode.jsonc")
	if err := os.WriteFile(config, []byte(`{
		// generated by setup
		"agents": {"lark": {"model": "opencode/primary#low"}, "deep": {"model": "opencode/deep#high"}},
		"plugins": [{"package": "./lark-model-router", "options": {"fallback": "opencode/fallback#low"}}]
	}`), 0o644); err != nil {
		t.Fatal(err)
	}
	// The clock check compares the host zone with the prompt zone, so use the
	// runner's zone instead of a developer workstation's.
	zone := systemTimeZone()
	if zone == "" {
		zone = "UTC"
	}
	return doctor{
		repo:         repo,
		configPath:   config,
		relay:        "relay.test",
		zone:         zone,
		relayProbe:   func(string) error { return nil },
		deviceStatus: func(string) (object, error) { return object{"min_free_heap": 100 << 10}, nil },
	}
}

func TestDoctorReportsAllGreen(t *testing.T) {
	t.Parallel()
	server := doctorFixture(t, nil)
	defer server.Close()
	env := doctorTestEnv(t)
	client := &cliClient{base: server.URL, http: server.Client()}
	var out, errOut strings.Builder
	if err := runDoctorWithClient(t.Context(), client, &out, &errOut, env); err != nil {
		t.Fatalf("doctor failed: %v\n%s", err, out.String())
	}
	text := out.String()
	for _, want := range []string{
		"ok    server", "ok    voice models", "ok    opencode models", "ok    firmware build",
		"ok    disk", "ok    library", "ok    deltachat", "ok    deltachat accounts",
		"ok    deltachat relay", "ok    terminal box3-test", "ok    tunnels",
		"ok    recent turns", "ok    clock", "opencode/primary#low",
	} {
		if !strings.Contains(text, want) {
			t.Errorf("missing %q in:\n%s", want, text)
		}
	}
	if strings.Contains(text, "\nfail  ") || strings.HasPrefix(text, "fail  ") ||
		strings.Contains(text, "\nwarn  ") || strings.HasPrefix(text, "warn  ") {
		t.Errorf("unexpected non-pass line:\n%s", text)
	}
}

func TestDoctorFailsOnBrokenServices(t *testing.T) {
	t.Parallel()
	server := doctorFixture(t, map[string]any{
		"/health": map[string]any{"ok": true, "opencode": true, "stt": false, "tts": true,
			"smart_turn": true, "deltachat": false},
		"/api/diagnostics": map[string]any{"recent_turns": []any{
			map[string]any{"error": true}, map[string]any{"error": true}, map[string]any{},
		}},
		"/api/library": map[string]any{"total_bytes": int64(100 << 30), "free_bytes": int64(1 << 30),
			"reserve_bytes": int64(20 << 30), "packs": []any{}},
	})
	defer server.Close()
	env := doctorTestEnv(t)
	client := &cliClient{base: server.URL, http: server.Client()}
	var out, errOut strings.Builder
	if err := runDoctorWithClient(t.Context(), client, &out, &errOut, env); err == nil {
		t.Fatalf("doctor should fail:\n%s", out.String())
	}
	for _, want := range []string{"fail  server", "fail  voice models", "fail  disk", "fail  recent turns"} {
		if !strings.Contains(out.String(), want) {
			t.Errorf("missing %q in:\n%s", want, out.String())
		}
	}
	if !strings.Contains(errOut.String(), "check(s) failed") {
		t.Errorf("missing failure summary: %q", errOut.String())
	}
}

func TestDoctorWarnsOnDrift(t *testing.T) {
	t.Parallel()
	offline := map[string]any{"id": "vocat-old", "board": "esp-vocat", "firmware": "9.9.8", "online": false, "ip": "127.0.0.2"}
	server := doctorFixture(t, map[string]any{
		"/api/terminals": map[string]any{"terminals": []any{
			offline,
			map[string]any{"id": "vocat-new", "board": "esp-vocat", "firmware": "9.9.8", "online": true, "ip": "127.0.0.3"},
		}},
		"/api/companions": map[string]any{"companions": []any{
			map[string]any{"id": "mint", "dc_account_id": 1},
			map[string]any{"id": "cake"},
		}},
		"/api/remote/tunnels": map[string]any{"tunnels": []any{
			map[string]any{"companion_id": "mint", "active": false},
		}},
	})
	defer server.Close()
	env := doctorTestEnv(t)
	env.deviceStatus = func(string) (object, error) { return object{"min_free_heap": 10 << 10}, nil }
	client := &cliClient{base: server.URL, http: server.Client()}
	var out, errOut strings.Builder
	if err := runDoctorWithClient(t.Context(), client, &out, &errOut, env); err != nil {
		t.Fatalf("warnings must not fail: %v\n%s", err, out.String())
	}
	text := out.String()
	for _, want := range []string{
		"warn  terminal vocat-old", "warn  terminal vocat-new",
		"warn  deltachat accounts", "warn  tunnels", "below 40 KiB",
	} {
		if !strings.Contains(text, want) {
			t.Errorf("missing %q in:\n%s", want, text)
		}
	}
}

func TestStripJSONComments(t *testing.T) {
	t.Parallel()
	in := "{\n// note\n\"url\": \"http://x//y\", /* block */ \"n\": 1\n}"
	got := strings.ReplaceAll(stripJSONComments(in), " ", "")
	got = strings.ReplaceAll(got, "\n", "")
	if got != `{"url":"http://x//y","n":1}` {
		t.Fatalf("stripJSONComments = %q", got)
	}
}
